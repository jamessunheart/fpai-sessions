#!/usr/bin/env bash
# bridge_to_codex — answered decision -> Codex build -> commit -> independent AI review -> surface.
# Pulls answered decisions tagged needs_build (server 162 = SSOT), writes a Codex spec,
# dispatches run_codex.sh (isolated worktree), then — because the Codex sandbox cannot
# write git metadata — COMMITS the worktree itself, runs the independent AI review
# (Claude Opus + protected-zone check), and surfaces the verdict to James's one chat.
# NEVER auto-merges. Ember/James merge after seeing the verdict.
#
# Usage: bridge_to_codex.sh [--dry-run]
# Kill:  touch ~/.config/fpai/decisions/.bridge_disabled
set -uo pipefail
REPO="$HOME/FPAI_Cockpit"; cd "$REPO"
DRY=0; [ "${1:-}" = "--dry-run" ] && DRY=1
HOST="${BRAIN_HOST:-root@162.0.208.88}"
WT_BASE="$HOME/.fpai-build-worktrees"
NOTIFY="tools/build_loop/notify_telegram.sh"
OL="tools/build_loop/ops_log.py"
loop_found=0
loop_built=0
loop_skipped=0
loop_reason="no work"

log_loop_run() {
  loop_skipped=$((loop_found - loop_built))
  [ "$loop_skipped" -lt 0 ] && loop_skipped=0
  if [ "$loop_reason" = "built" ] && [ "$loop_built" -eq 0 ]; then
    loop_reason="no work"
  fi
  python3 "$OL" build_loop loop_run "$loop_reason" '$0' '' '' \
    "found=$loop_found" "built=$loop_built" "skipped=$loop_skipped" "reason=$loop_reason" 2>/dev/null || true
}
trap log_loop_run EXIT

if [ -f "$HOME/.config/fpai/decisions/.bridge_disabled" ]; then
  loop_reason="disabled"
  echo "bridge disabled"
  exit 0
fi

REMOTE='ENVFILE=$(systemctl show sh-brain-tgbot -p EnvironmentFiles 2>/dev/null | sed -E "s/EnvironmentFiles=//; s/ .*//"); cd /opt/sh-brain-src && set -a; . "$ENVFILE" 2>/dev/null; set +a; ./.venv/bin/python -m curator.decisions pending-builds'
PENDING=$(ssh -o BatchMode=yes -o ConnectTimeout=20 "$HOST" "$REMOTE" 2>/dev/null | grep -E '^\{')
[ -z "$PENDING" ] && { echo "no decisions awaiting a build"; exit 0; }

mkdir -p core/BUILD/specs
IDS=()
while IFS= read -r line; do
  [ -z "$line" ] && continue
  DID=$(printf '%s' "$line" | python3 -c 'import sys,json;print(json.load(sys.stdin)["id"])')
  SLUG=$(printf '%s' "$line" | python3 -c 'import sys,json,re;q=json.load(sys.stdin)["question"];print(re.sub(r"[^a-z0-9]+","-",q.lower())[:32].strip("-"))')
  SPECID="SPEC_${DID}_${SLUG}"
  SPEC="core/BUILD/specs/${SPECID}.md"
  python3 - "$line" "$SPEC" <<'PY'
import sys, json
d = json.loads(sys.argv[1]); path = sys.argv[2]
open(path, "w").write(f"""# SPEC_{d['id']}_auto — {d['question'][:60]}

Auto-generated by the decision->Codex bridge from answered decision {d['id']}.

## Build
{d.get('build_spec') or '(no explicit build instruction — implement what the answer + proof_expected require)'}

## Context — the decision
- **Question:** {d['question']}
- **James's answer:** {d['answer']}
- **Proof expected:** {d.get('proof_expected') or '(see answer)'}

## Contract
Follow `docs/codex/SESSION_CONTRACT.md`. Branch off `feat/headless-build` (never main).
Register in `core/BUILD/REGISTRY.json` (status building->done). Tests required.
Do NOT push or open PRs — Ember merges after the independent AI review.

## Done / Proof
{d.get('proof_expected') or 'Implement, test, set REGISTRY status done, report branch + test count.'}
""")
print("wrote", path)
PY
  ssh -o BatchMode=yes -o ConnectTimeout=15 "$HOST" \
    'ENVFILE=$(systemctl show sh-brain-tgbot -p EnvironmentFiles 2>/dev/null | sed -E "s/EnvironmentFiles=//; s/ .*//"); cd /opt/sh-brain-src && set -a; . "$ENVFILE" 2>/dev/null; set +a; ./.venv/bin/python -m curator.decisions mark-built '"$DID" >/dev/null 2>&1
  IDS+=("$SPECID")
done <<< "$PENDING"
loop_found=${#IDS[@]}

echo "specs written: ${#IDS[@]}"
if [ "$DRY" = "1" ]; then loop_reason="disabled"; echo "(dry-run — Codex NOT dispatched)"; exit 0; fi
[ ${#IDS[@]} -eq 0 ] && exit 0

# Dispatch to Codex (builds in isolated worktrees on build/<id> branches).
echo "dispatching to Codex…"
bash tools/build_loop/run_codex.sh || echo "run_codex returned non-zero (check core/BUILD/results)"
loop_reason="built"

# For each decision-spec built this run: commit the worktree (Codex sandbox can't write
# git), run the INDEPENDENT AI review (+ protected-zone block), surface the verdict.
for SPECID in "${IDS[@]}"; do
  WT="$WT_BASE/$SPECID"; BR="build/$SPECID"
  if [ ! -d "$WT" ]; then echo "no worktree for $SPECID (not built this run)"; continue; fi
  if [ -n "$(git -C "$WT" status --porcelain 2>/dev/null)" ]; then
    git -C "$WT" add -A 2>/dev/null
    git -C "$WT" commit -q -m "build($SPECID): auto-committed by bridge (Codex sandbox cannot write git)" 2>/dev/null || true
  fi
  if ! git -C "$REPO" rev-parse --verify "$BR" >/dev/null 2>&1; then
    echo "branch $BR missing — Codex produced no commit; skipping review."
    [ -x "$NOTIFY" ] && "$NOTIFY" "⚠️ Build $SPECID produced no committable branch — held for manual review." >/dev/null 2>&1 || true
    continue
  fi
  REVIEW=$(python3 tools/merge/ai_review.py "$BR" 2>&1); RC=$?
  echo "review[$SPECID] rc=$RC: $REVIEW"
  DID=$(echo "$SPECID" | sed -E 's/^SPEC_(d[0-9]+)_.*/\1/')
  # record the build result on the decision so "merge d00X" from the phone can find it
  if [ "$RC" = "0" ]; then BSTATUS=built; elif [ "$RC" = "2" ]; then BSTATUS=rejected; else BSTATUS=changes; fi
  ssh -o BatchMode=yes -o ConnectTimeout=15 "$HOST" \
    'ENVFILE=$(systemctl show sh-brain-tgbot -p EnvironmentFiles 2>/dev/null | sed -E "s/EnvironmentFiles=//; s/ .*//"); cd /opt/sh-brain-src && set -a; . "$ENVFILE" 2>/dev/null; set +a; ./.venv/bin/python -m curator.decisions set-build-result '"$DID $BR $BSTATUS" >/dev/null 2>&1 || true
  loop_built=$((loop_built+1))
  [ -x "$NOTIFY" ] || continue
  if [ "$RC" = "0" ]; then
    "$NOTIFY" "✅ Built + AI-APPROVED · [$DID] $SPECID
$REVIEW
Ready to merge. Reply <code>merge $DID</code> to merge it (into feat/headless-build), or <code>reverse $DID</code> to drop it. (never auto-merged to main)" >/dev/null 2>&1 || true
  elif [ "$RC" = "2" ]; then
    "$NOTIFY" "🔴 BLOCKED — touches the protected audit layer · [$DID] $SPECID
$REVIEW
Escalated to you. Not merged." >/dev/null 2>&1 || true
  else
    "$NOTIFY" "⚠️ Built, but independent AI flagged changes · [$DID] $SPECID
$REVIEW
Held for your review. Reply <code>reverse $DID</code> to drop it. Not merged." >/dev/null 2>&1 || true
  fi
done
