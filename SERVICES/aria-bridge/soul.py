def detect_dimension(message: str) -> str:
    """Detect which dimension the message is coming from."""
    message_lower = message.lower()
    
    scores = {}
    for dim_key, dim in DIMENSIONS.items():
        score = sum(1 for indicator in dim["indicators"] if indicator in message_lower)
        scores[dim_key] = score
    
    if max(scores.values()) == 0:
        return "mental"  # Default to mental/analytical
    
    return max(scores, key=scores.get)


def detect_mode(message: str) -> str:
    """Detect which operating mode is appropriate."""
    message_lower = message.lower()
    
    scores = {}
    for mode_key, mode in MODES.items():
        score = sum(1 for indicator in mode["indicators"] if indicator in message_lower)
        scores[mode_key] = score
    
    if max(scores.values()) == 0:
        return "sensemaking"  # Default to reflection
    
    return max(scores, key=scores.get)


